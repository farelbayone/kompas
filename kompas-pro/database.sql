CREATE DATABASE IF NOT EXISTS kompas CHARACTER SET utf8mb4;
USE kompas;

CREATE TABLE IF NOT EXISTS users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(20) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  has_data TINYINT(1) NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS transactions (
  user_id INT NOT NULL, id BIGINT UNSIGNED NOT NULL,
  type VARCHAR(3) NOT NULL, amount INT NOT NULL, category VARCHAR(50), trx_date DATE NOT NULL, note VARCHAR(255),
  PRIMARY KEY (user_id, id), INDEX (user_id, trx_date),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS tasks (
  user_id INT NOT NULL, id BIGINT UNSIGNED NOT NULL,
  title VARCHAR(200) NOT NULL, status VARCHAR(10) NOT NULL DEFAULT 'todo', priority CHAR(1) NOT NULL DEFAULT 'm', due_date DATE NULL,
  PRIMARY KEY (user_id, id),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS habits (
  user_id INT NOT NULL, id BIGINT UNSIGNED NOT NULL, name VARCHAR(100) NOT NULL,
  PRIMARY KEY (user_id, id),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS habit_logs (
  user_id INT NOT NULL, habit_id BIGINT UNSIGNED NOT NULL, log_date DATE NOT NULL,
  PRIMARY KEY (user_id, habit_id, log_date),
  FOREIGN KEY (user_id, habit_id) REFERENCES habits(user_id, id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS notes (
  user_id INT NOT NULL, id BIGINT UNSIGNED NOT NULL,
  title VARCHAR(150) NOT NULL, body TEXT, pinned TINYINT(1) NOT NULL DEFAULT 0,
  PRIMARY KEY (user_id, id),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
